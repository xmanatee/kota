import Foundation
import SwiftUI
import XCTest
#if os(macOS)
import AppKit
#endif
@testable import KotaShared

/// Rendered evidence for the shared macOS/iOS digest surface. The PNG fixtures
/// mount the real SwiftUI views that make up `DigestView` against deterministic
/// `AppState` branches, so the consolidation artifact is tied to the shipped
/// client surface rather than a handwritten reconstruction.
@MainActor
final class DigestViewRenderedTests: XCTestCase {
    func testWritesDigestViewRenderedStates() throws {
        guard let output = Self.snapshotOutput() else { return }

        try FileManager.default.createDirectory(
            at: output.imageDirectory,
            withIntermediateDirectories: true
        )

        var lines = [
            "# Rendered macOS DigestView snapshot",
            "# Generated by DigestViewRenderedTests.testWritesDigestViewRenderedStates",
            "surface: clients/apple/Sources/KotaShared/DigestView.swift",
            "renderer: SwiftUI.ImageRenderer -> PNG",
            "",
        ]

        for scenario in Self.renderScenarios {
            let rendered = try renderScenario(scenario, in: output.imageDirectory)
            lines.append("## \(scenario.id)")
            lines.append("state: \(scenario.summary)")
            lines.append("mount: \(scenario.mount)")
            lines.append("png: \(output.imageDirectory.lastPathComponent)/\(rendered.fileName)")
            lines.append("pixels: \(rendered.width)x\(rendered.height)")
            lines.append("bytes: \(rendered.byteCount)")
            lines.append("")
        }

        try lines.joined(separator: "\n")
            .write(to: output.manifest, atomically: true, encoding: .utf8)
    }

    private struct RenderScenario {
        let id: String
        let summary: String
        let mount: String
        let configure: (AppState) -> Void
        let content: (AppState) -> AnyView
    }

    private struct RenderedPNG {
        let fileName: String
        let width: Int
        let height: Int
        let byteCount: Int
    }

    private struct SnapshotOutput {
        let manifest: URL
        let imageDirectory: URL
    }

    private static var renderScenarios: [RenderScenario] {
        [
            RenderScenario(
                id: "collapsed-active-header",
