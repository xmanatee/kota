    private func renderScenario(_ scenario: RenderScenario, in directory: URL) throws -> RenderedPNG {
#if os(macOS)
        let state = AppState(startPollingOnInit: false)
        scenario.configure(state)

        let content = scenario.content(state)
            .environmentObject(state)
            .padding(12)
            .frame(width: 520, alignment: .leading)
            .frame(minHeight: 88, alignment: .leading)
            .background(Color(nsColor: .windowBackgroundColor))

        let renderer = ImageRenderer(content: content)
        renderer.proposedSize = ProposedViewSize(width: 520, height: 180)
        renderer.scale = 2

        guard let image = renderer.cgImage else {
            XCTFail("ImageRenderer did not produce a CGImage for \(scenario.id)")
            throw SnapshotError.renderFailed(scenario.id)
        }

        let rep = NSBitmapImageRep(cgImage: image)
        guard let png = rep.representation(using: NSBitmapImageRep.FileType.png, properties: [:]) else {
            XCTFail("NSBitmapImageRep did not produce PNG data for \(scenario.id)")
            throw SnapshotError.renderFailed(scenario.id)
        }

        let url = directory.appendingPathComponent("\(scenario.id).png")
        try png.write(to: url, options: Data.WritingOptions.atomic)
        XCTAssertGreaterThan(png.count, 1_000, "Rendered PNG for \(scenario.id) should not be blank")

        return RenderedPNG(
            fileName: url.lastPathComponent,
            width: image.width,
            height: image.height,
            byteCount: png.count
        )
#else
        throw XCTSkip("DigestView PNG snapshots are generated by the macOS test host")
#endif
    }

    private enum SnapshotError: Error {
        case renderFailed(String)
    }

    private static func snapshotOutput() -> SnapshotOutput? {
        let env = ProcessInfo.processInfo.environment
        guard let runDir = env["KOTA_RUN_DIR"], !runDir.isEmpty else { return nil }
        let surfaceDirectory = URL(fileURLWithPath: runDir)
            .appendingPathComponent("digest-consolidation")
            .appendingPathComponent("surface-runtime-evidence")
            .appendingPathComponent("macos")
        return SnapshotOutput(
            manifest: surfaceDirectory.appendingPathComponent("digest-view-rendered-states.txt"),
            imageDirectory: surfaceDirectory.appendingPathComponent("digest-view-rendered-states")
        )
    }
}
