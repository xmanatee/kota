import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import ts from "typescript";
import { UI_SURFACE_SOURCE } from "./ui-surface-schema.mjs";

function isContractStatement(statement) {
  if (ts.isTypeAliasDeclaration(statement)) {
    return statement.name.text.startsWith("Ui");
  }
  if (!ts.isVariableStatement(statement)) return false;
  return statement.declarationList.declarations.some(
    (declaration) => ts.isIdentifier(declaration.name) && declaration.name.text === "UI_SURFACE_PROTOCOL_VERSION",
  );
}

function printContractDeclarations(root) {
  const path = resolve(root, UI_SURFACE_SOURCE);
  const source = ts.createSourceFile(
    path,
    readFileSync(path, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  return source.statements
    .filter(isContractStatement)
    .map((statement) => printer.printNode(ts.EmitHint.Unspecified, statement, source))
    .join("\n\n");
}

export function generateTypeScriptBinding(root, schema) {
  const template = readFileSync(
    resolve(import.meta.dirname, "ui-surface-typescript-runtime.template"),
    "utf8",
  );
  const runtime = template.replace("__SCHEMA_JSON__", JSON.stringify(JSON.stringify(schema)));
  return [
    "// Generated by `pnpm build:ui-bindings` from src/core/daemon/ui-surface.ts.",
    "// Do not edit this file directly.",
    "",
    'import { ContractDecodeError, fail } from "./decoder-common";',
    "",
    printContractDeclarations(root),
    runtime,
  ].join("\n");
}
